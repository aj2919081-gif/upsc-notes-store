PRICE = 39
ORIG_PRICE = 99

conn = sqlite3.connect(DB)
conn.row_factory = sqlite3.Row

# check existing history notes to avoid duplicate titles
existing_titles = set(r["title"] for r in conn.execute("SELECT title FROM notes WHERE subject_slug='history'"))

uploaded = 0
skipped = 0
for fname, title, desc in FILES:
    src = os.path.join(SRC, fname)
    if not os.path.exists(src):
        print(f"SKIP (file missing): {fname}")
        skipped += 1
        continue
    if title in existing_titles:
        print(f"SKIP (duplicate): {title}")
        skipped += 1
        continue

    stored = f"{uuid.uuid4().hex}.html"
    dst = os.path.join(HTML_DST, stored)
    shutil.copy2(src, dst)

    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    conn.execute(
        """INSERT INTO notes
           (title, subject_slug, description, price, original_price, file_type,
            file_path, original_name, pages, language, featured, created_at)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
        (title, "history", desc, PRICE, ORIG_PRICE, "html",
         f"uploads/html/{stored}", fname, None, "Hindi", 0, now),
    )
    uploaded += 1

conn.commit()
conn.close()
print(f"\n✅ {uploaded} notes uploaded, {skipped} skipped.")
